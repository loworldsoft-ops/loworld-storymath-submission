import { WallpaperItem } from './wallpaper.model';

function createSolidColorWallpaper(
  id: string,
  name: string,
  tag: string,
  color: string,
  description: string,
  accentColor: string,
): WallpaperItem {
  const svgDataUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" width="300" height="200" viewBox="0 0 300 200"><rect width="100%" height="100%" fill="${color}"/></svg>`
  )}`;

  return {
    id,
    name,
    tag,
    category: 'solid',
    description,
    desktopUrl: svgDataUrl,
    mobileUrl: svgDataUrl,
    thumbnailUrl: svgDataUrl,
    accentColor,
    isSolidColor: true,
    solidColorHex: color,
  };
}

