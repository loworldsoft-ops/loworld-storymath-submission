/** ID 또는 이름/별칭으로 도감 항목을 빠르게 검색하는 인덱스 맵 */
export const RPG_LORE_CHARACTER_BY_KEY = new Map<string, LoreCharacterEntry>();

for (const entry of LORE_CHARACTER_CODEX) {
  RPG_LORE_CHARACTER_BY_KEY.set(entry.id.toLowerCase(), entry);
  RPG_LORE_CHARACTER_BY_KEY.set(entry.name.toLowerCase(), entry);
  RPG_LORE_CHARACTER_BY_KEY.set(entry.englishName.toLowerCase(), entry);
  if (entry.rpgMonsterId) {
    RPG_LORE_CHARACTER_BY_KEY.set(entry.rpgMonsterId.toLowerCase(), entry);
  }
  for (const alias of entry.aliases) {
    RPG_LORE_CHARACTER_BY_KEY.set(alias.toLowerCase(), entry);
  }
}

/** 주어진 키(ID, 한글 이름, 영문 이름, 몬스터 ID 등)로 도감 엔트리를 탐색 */
export function findRpgLoreCharacter(key: string | null | undefined): LoreCharacterEntry | null {
  if (!key) return null;
  const normalized = key.trim().toLowerCase();
  if (RPG_LORE_CHARACTER_BY_KEY.has(normalized)) {
    return RPG_LORE_CHARACTER_BY_KEY.get(normalized)!;
  }
  // 부분 매칭 시도
  for (const [k, entry] of RPG_LORE_CHARACTER_BY_KEY.entries()) {
    if (k.length >= 2 && (normalized.includes(k) || k.includes(normalized))) {
      return entry;
    }
  }
  return null;
}
