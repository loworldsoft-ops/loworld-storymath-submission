/** 소림사, 사천당가, 천마신교, 무당파, 남궁세가 핵심 스킬 프리셋 */
export function generateGenericMartialSectSkills(
  sectKey: string,
  sectName: string,
  tree1Label: string,
  tree2Label: string,
  tree3Label: string,
  primaryKind: 'physical' | 'magic',
): RpgSkillRegistryEntry[] {
  const trees = [
    { page: 1, label: tree1Label },
    { page: 2, label: tree2Label },
    { page: 3, label: tree3Label },
  ];

  const levels = [1, 6, 12, 18, 24, 30] as const;
  const list: RpgSkillRegistryEntry[] = [];

  for (const tree of trees) {
    for (let rowIdx = 0; rowIdx < levels.length; rowIdx++) {
      const reqlevel = levels[rowIdx];
      const col = (rowIdx % 3) + 1;
      const skillId = `${sectKey}-t${tree.page}-r${rowIdx + 1}-c${col}`;
      const nameKo = `${sectName} ${tree.label} ${reqlevel >= 30 ? '오의' : `초식 ${rowIdx + 1}`}`;

      list.push({
        id: skillId,
        rpgName: `${sectKey} ${tree.label} ${rowIdx + 1}`,
        nameKo,
        descriptionKo: `${sectName}의 비전 [${tree.label}] 계열 무학. 심후한 공력으로 적을 타격한다.`,
        charclass: sectKey,
        discipline: sectKey as CharacterClass,
        treePage: tree.page,
        treeRow: rowIdx + 1,
        treeColumn: col,
        treeLabelEn: `${sectKey} Tree ${tree.page}`,
        treeLabelKo: tree.label,
        reqlevel,
        maxLevel: 20,
        prerequisites: rowIdx > 0 ? [`${sectKey}-t${tree.page}-r${rowIdx}-c${((rowIdx - 1) % 3) + 1}`] : [],
        prerequisiteRpgNames: [],
        synergies: [],
        kind: rowIdx === 5 ? 'active' : (rowIdx % 2 === 0 ? 'active' : 'passive'),
        type: primaryKind,
        manaLevel1: 5 + rowIdx * 3,
        manaLevel20: 15 + rowIdx * 5,
        iconId: rowIdx === 5 ? 'flash-strike' : (primaryKind === 'physical' ? 'sword-wind' : 'fireball'),
      });
    }
  }

  return list;
}

